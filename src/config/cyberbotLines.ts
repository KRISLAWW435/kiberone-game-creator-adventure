export function pickCyberBotLine(
  stageId: number,
  context: CyberBotContext,
  lastLine?: string
): string {
  const bank = CYBERBOT_STAGE_LINES[stageId] || CYBERBOT_STAGE_LINES[1];
  const options = bank[context] || bank.enter;
  if (options.length === 1) return options[0];

  const nonRepeating = lastLine ? options.filter((line) => line !== lastLine) : options;
  const pool = nonRepeating.length > 0 ? nonRepeating : options;
  // Deterministic rotation based on stageId + context length so render stays pure without flicker
  const index = (stageId + context.length) % pool.length;
  return pool[index];
}

export function getEmotionForContext(context: CyberBotContext, stageId: number): MascotEmotion {
  if (stageId === 10 && (context === 'enter' || context === 'success')) return 'victory';
  switch (context) {
    case 'success':
      return 'joy';
    case 'waiting':
      return 'joy';
    case 'error':
    case 'struggle':
      return 'thinking';
    case 'action':
      return stageId === 7 ? 'surprise' : 'thinking';
    case 'enter':
    default:
      return stageId === 7 ? 'surprise' : 'support';
  }
}
